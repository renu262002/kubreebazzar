export function generate48Products(): Product[] {
  const now = new Date().toISOString();

  return SEED_CATALOG_ITEMS.map((item, index) => {
    const originalPrice =
      item.originalPrice !== undefined
        ? item.originalPrice
        : item.discountPercent > 0 && item.price > 0
          ? Math.round(item.price / (1 - item.discountPercent / 100))
          : item.price;

    const defaultVariants =
      item.variants !== undefined
        ? item.variants
        : item.noDemoDefaults
          ? []
          : [
              {
                id: `var-${item.id}-std`,
                name: 'Standard Edition',
                label: 'Standard Edition',
                priceDelta: 0,
                stock: item.stock,
              },
            ];

    const defaultSpecs =
      item.specs !== undefined
        ? item.specs
        : item.noDemoDefaults
          ? []
          : [
              { label: 'Category', value: getCategoryDisplayName(item.category) },
              { label: 'Brand', value: item.brand },
              { label: 'Quality Guarantee', value: '100% Genuine KubreeBazzar Inspected' },
            ];

    return {
      id: item.id,
      name: item.name,
      ...(item.tamilName ? { tamilName: item.tamilName } : {}),
      slug: item.slug,
      category: item.category,
      subcategory: item.subcategory,
      subSubcategory: item.subSubcategory,
      brand: item.brand,
      price: item.price,
      originalPrice,
      discountPercent: item.discountPercent,
      shortDescription: item.shortDescription,
      description: item.description,
      images:
        item.images && item.images.length > 0 ? item.images : [item.image],
      modelType: item.modelType,
      has3DModel: item.has3DModel ?? false,
      variants: defaultVariants,
      specs: defaultSpecs,
      vehicleDetails: item.vehicleDetails,
      stock: item.stock,
      rating: item.noDemoDefaults
        ? 0
        : Number((4.6 + (index % 5) * 0.08).toFixed(2)),
      reviewCount: item.noDemoDefaults ? 0 : 15 + index * 3,
      isDemoRating: !item.noDemoDefaults,
      featured: Boolean(item.featured),
      trending: Boolean(item.trending),
      bestSeller: Boolean(item.bestSeller),
      newArrival: Boolean(item.newArrival),
      tag: item.tag,
      ...(item.tags ? { tags: item.tags } : {}),
      enabled: item.enabled ?? true,
      ...(item.isDraft ? { isDraft: item.isDraft } : {}),
      ...(item.isBundle ? { isBundle: item.isBundle } : {}),
      ...(item.bundleItems ? { bundleItems: item.bundleItems } : {}),
      ...(item.usageInstructions
        ? { usageInstructions: item.usageInstructions }
        : {}),
      ...(item.ageSuitability ? { ageSuitability: item.ageSuitability } : {}),
      createdAt: now,
    };
  });
}
